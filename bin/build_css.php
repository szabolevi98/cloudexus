<?php

/**
 * Concatenates the layered CSS source files under src/View/Css into the
 * single web/assets/css/app.css that the app actually links. There is no
 * Sass/PostCSS/bundler step — this is the entire "build".
 *
 * The order below is significant (later files can rely on custom properties
 * and base rules defined earlier) and must be kept in sync by hand whenever
 * a new source file is added.
 *
 * Usage: php bin/build_css.php
 */

$root = dirname(__DIR__);
$srcDir = $root . '/src/View/Css';
$outFile = $root . '/web/assets/css/app.css';

$files = [
    'base/variables.css',
    'base/reset.css',
    'layout/shell.css',
    'components/card.css',
    'components/nav.css',
    'components/table.css',
    'components/user-pill.css',
    'components/code-block.css',
    'components/theme.css',
    'components/palette.css',
    'pages/auth.css',
    'pages/api-docs.css',
    'pages/permissions.css',
    'pages/two-factor.css',
];

$output = "/* Auto-generated by bin/build_css.php — do not edit directly.\n"
    . " * Edit the source files under src/View/Css/ instead, then re-run the script. */\n\n";

foreach ($files as $file) {
    $path = $srcDir . '/' . $file;
    if (!is_file($path)) {
        fwrite(STDERR, "Missing CSS source file: $file\n");
        exit(1);
    }
    $output .= rtrim(file_get_contents($path)) . "\n\n";
}

file_put_contents($outFile, rtrim($output) . "\n");

echo "Built $outFile from " . count($files) . " source files.\n";
